#!/usr/bin/env python3
"""Write vercel-env-vars.tf: every environment variable Vercel holds today for the projects vercel-env.tf manages, by its
Vercel id, with its name, targets and sensitivity. Never a value: the values come from the vercel-env/<site>/<target>
containers at plan time.

    scripts/vercel-env-inventory.py           # rewrite vercel-env-vars.tf from the Vercel API
    scripts/vercel-env-inventory.py --check   # exit 1 if the file differs from what the API says now

Run it after adding or removing a variable in one of these projects (a new variable also needs its value in that
target's container), then plan. It reads vercel-admin-token (jumpbox role only) and prints no secret.
"""
import argparse
import json
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "vercel-env-vars.tf"
# Kept equal to local.vercel_env_projects in vercel-env.tf (scripts/test-vercel-env.py checks).
PROJECTS = {
    "imagine": ("prj_MNp1CoEL7jqd3ufUb0lL98vTMBTV", "team_fYexi4KRmIrq9wtYsiXs9e9H"),
    "nest-step": ("prj_UEBlk5ovC3cPF0oaXwgZyGuRQtId", "team_luQ5Id7cevXQ5kBbxzV7Jk2B"),
    "remote-claw": ("prj_qUeYYc7P87JmsQUipJG0m0kqmYbM", "team_fYexi4KRmIrq9wtYsiXs9e9H"),
}
TARGETS = ("development", "preview", "production")


def render(variables):
    """variables: {"site/envid": {"key", "target" (sorted list), "sensitive"}} -> the file's text, deterministic."""
    lines = [
        "# vercel-env-vars.tf: GENERATED by scripts/vercel-env-inventory.py from the Vercel API. Do not edit by hand.",
        "# Every environment variable Vercel holds for the projects vercel-env.tf manages, by Vercel id: name, targets and",
        "# whether it is sensitive. Never a value: values come from the vercel-env/<site>/<target> containers at plan time.",
        "locals {",
        "  vercel_env_vars = {",
    ]
    order = sorted(variables, key=lambda i: (i.split("/")[0], variables[i]["key"], i))
    width = max((len(json.dumps(i)) for i in order), default=0)   # terraform fmt aligns the = of a run of entries
    for ident in order:
        v = variables[ident]
        target = ", ".join(json.dumps(t) for t in v["target"])
        lines.append(f'    {json.dumps(ident).ljust(width)} = {{ key = {json.dumps(v["key"])}, target = [{target}], sensitive = {str(v["sensitive"]).lower()} }}')
    lines += ["  }", "}", ""]
    return "\n".join(lines)


def fetch(token):
    variables = {}
    for site, (project, team) in PROJECTS.items():
        req = urllib.request.Request(f"https://api.vercel.com/v10/projects/{project}/env?teamId={team}",
                                     headers={"Authorization": "Bearer " + token})
        envs = json.loads(urllib.request.urlopen(req, timeout=30).read())["envs"]
        for e in envs:
            target = sorted(t for t in (e.get("target") or []) if t in TARGETS)
            if e.get("gitBranch") or e.get("customEnvironmentIds") or not target:
                raise SystemExit(f"{site}: {e['key']} is branch-scoped or in a custom environment; vercel-env.tf does not model that")
            variables[f"{site}/{e['id']}"] = {"key": e["key"], "target": target, "sensitive": e.get("type") == "sensitive"}
    return variables


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    import boto3
    token = boto3.client("secretsmanager", region_name="us-west-1").get_secret_value(SecretId="vercel-admin-token")["SecretString"].strip()
    text = render(fetch(token))
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        print("vercel-env-vars.tf is current" if current == text else "vercel-env-vars.tf differs from the Vercel API: re-run without --check")
        return 0 if current == text else 1
    OUT.write_text(text)
    print(f"wrote {OUT.name}: {text.count(' = { key = ')} variables")
    return 0


if __name__ == "__main__":
    sys.exit(main())
