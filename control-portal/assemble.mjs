import {readFile, writeFile} from 'node:fs/promises';

const ui = await readFile(new URL('./portal-ui.mjs', import.meta.url), 'utf8');
const backend = await readFile(new URL('./portal-backend.mjs', import.meta.url), 'utf8');
if (/^import\s/m.test(ui + backend)) throw new Error('Worker modules must be self-contained');
const source = `// Generated by control-portal/assemble.mjs; edit the reviewed source modules.\n${ui}\n${backend}\nexport default {fetch(request, env, ctx) { return handlePortalRequest(request, env, pathname => pathname === '/doctor' ? renderPortal() : renderMdmCredentialsPortal(), {access: ctx.access}); }};\n`;
const artifact = new URL('./index.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(artifact, 'utf8') !== source) throw new Error('Run node control-portal/assemble.mjs before deploying');
  console.log('Deployment artifact matches reviewed modules');
} else {
  await writeFile(artifact, source);
  console.log('Assembled owner-private Cloudflare Worker');
}
